CREATE OR REPLACE FUNCTION puko_olayi_denetle() RETURNS trigger
  LANGUAGE plpgsql
  AS $$
BEGIN
  IF NEW.karar_veren_kisi_id IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM kisi k WHERE k.id = NEW.karar_veren_kisi_id AND k.kurum_id = NEW.kurum_id) THEN
    RAISE EXCEPTION 'Önlem kararını veren kişi bu kurumda değil.' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.tur = 'onlem_secildi' AND NOT EXISTS (
    SELECT 1 FROM puko_olayi p WHERE p.kurum_id = NEW.kurum_id AND p.puko_id = NEW.puko_id AND p.tur = 'acildi'
  ) THEN
    RAISE EXCEPTION 'Açılmamış PÜKÖ döngüsüne önlem yazılamaz.' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.tur = 'kapandi' AND NOT EXISTS (
    SELECT 1 FROM puko_olayi p WHERE p.kurum_id = NEW.kurum_id AND p.puko_id = NEW.puko_id AND p.tur = 'onlem_secildi'
  ) THEN
    RAISE EXCEPTION 'Önlemi seçilmemiş PÜKÖ döngüsü kapatılamaz.' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$$;
