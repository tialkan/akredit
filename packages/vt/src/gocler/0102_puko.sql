-- Her satır bir olaydır: kartın açılması, önlemin seçilmesi, döngünün kapanması. Kayıtlar yalnız eklenir
-- (ilke 4): uygulama güncelleyemez, silemez; düzeltme yeni olayla yapılır. Durum olaylardan türetilir.
-- Kurallar (son savunma hattı):
--   - kiracı yalıtımı (RLS, FORCE);
--   - bir döngüde her olay türü en çok bir kez (aynı karta iki karar yazılamaz);
--   - önlem seçimi olayında karar veren kişi zorunlu, olay içeriğindeki karar verenle aynı ve aynı kurumdan;
--     öteki olaylarda kişi alanı boş (ilke 3: katman 2 kararı kişinindir);
--   - önlem ancak açılmış döngüde, kapanış ancak önlemi seçilmiş döngüde eklenebilir.

CREATE TABLE puko_olayi (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  kurum_id uuid NOT NULL REFERENCES kurum(id),
  sira bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  puko_id text NOT NULL,
  tur text NOT NULL,
  olay jsonb NOT NULL,
  karar_veren_kisi_id uuid REFERENCES kisi(id),
  zaman timestamptz NOT NULL,
  olusturma timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT puko_olayi_tur CHECK (tur IN ('acildi', 'onlem_secildi', 'kapandi')),
  CONSTRAINT puko_olayi_icerik CHECK (olay ->> 'tur' = tur AND olay ->> 'pukoId' = puko_id),
  CONSTRAINT puko_olayi_karar_veren CHECK (
    (tur = 'onlem_secildi' AND karar_veren_kisi_id IS NOT NULL AND olay ->> 'kararVeren' = karar_veren_kisi_id::text)
    OR (tur <> 'onlem_secildi' AND karar_veren_kisi_id IS NULL)
  )
);
