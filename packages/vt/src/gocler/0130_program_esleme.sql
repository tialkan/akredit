-- ÖDR tabloları için kurumun girdiği eşlemeler: dersin kategorisi ya da türü (çerçeveye göre), program
-- çıktısının kapsadığı kurul çıktıları ve yarıyıl başına seçmeli ders yer sayısı. Akredit bu eşlemeleri
-- tahmin etmez. Bir kayıt ya öneridir (YZ ya da kişi yazar, tabloya girmez) ya da karardır (kurum
-- kullanıcısı adıyla, zamanıyla ve dayanağıyla verir; tabloya yalnız karar girer).
-- Kurallar (son savunma hattı):
--   - kayıtlar yalnız eklenir (ilke 4): düzeltme aynı anahtara yeni karardır, son karar geçerlidir;
--   - kiracı yalıtımı (RLS, FORCE);
--   - kararda karar veren kişi ve boş olmayan dayanak zorunlu; öneride karar veren boş;
--   - karar veren kişi ve program aynı kurumdan;
--   - seçmeli yer sayısı çerçeveden bağımsızdır (cerceve_kod boş), öteki türlerde çerçeve zorunlu;
--   - değerin biçimi türe uyar: kategori metin, kurul eşlemesi metin dizisi, yer sayısı negatif olmayan tam sayı.

CREATE TABLE program_esleme (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  kurum_id uuid NOT NULL REFERENCES kurum(id),
  sira bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  program_id uuid NOT NULL REFERENCES program(id),
  cerceve_kod text,
  tur text NOT NULL,
  anahtar text NOT NULL,
  deger jsonb NOT NULL,
  durum text NOT NULL,
  uretici text NOT NULL,
  karar_veren_kisi_id uuid REFERENCES kisi(id),
  dayanak text,
  zaman timestamptz NOT NULL,
  olusturma timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT program_esleme_tur CHECK (tur IN ('ders_kategorisi', 'pc_kurul', 'secmeli_yer')),
  CONSTRAINT program_esleme_durum CHECK (durum IN ('oneri', 'karar')),
  CONSTRAINT program_esleme_uretici CHECK (uretici IN ('yz', 'kisi')),
  CONSTRAINT program_esleme_anahtar CHECK (length(anahtar) BETWEEN 1 AND 100),
  CONSTRAINT program_esleme_cerceve CHECK (
    (tur = 'secmeli_yer' AND cerceve_kod IS NULL) OR (tur <> 'secmeli_yer' AND length(cerceve_kod) > 0)
  ),
  CONSTRAINT program_esleme_deger CHECK (
    (tur = 'ders_kategorisi' AND jsonb_typeof(deger) = 'string')
    OR (tur = 'pc_kurul' AND jsonb_typeof(deger) = 'array')
    OR (tur = 'secmeli_yer' AND jsonb_typeof(deger) = 'number' AND (deger #>> '{}')::numeric >= 0
        AND (deger #>> '{}')::numeric = floor((deger #>> '{}')::numeric))
  ),
  CONSTRAINT program_esleme_karar CHECK (
    (durum = 'karar' AND uretici = 'kisi' AND karar_veren_kisi_id IS NOT NULL AND length(btrim(dayanak)) > 0)
    OR (durum = 'oneri' AND karar_veren_kisi_id IS NULL)
  )
);
