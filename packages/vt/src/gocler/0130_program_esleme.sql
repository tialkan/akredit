CREATE OR REPLACE FUNCTION program_esleme_denetle() RETURNS trigger
  LANGUAGE plpgsql
  AS $$
BEGIN
  -- Başka kurumun satırını satır güvenliği reddeder (42501); denetim yalnız etkin kurumun satırına bakar.
  IF NEW.kurum_id IS DISTINCT FROM etkin_kurum() THEN
    RETURN NEW;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM program p WHERE p.id = NEW.program_id AND p.kurum_id = NEW.kurum_id) THEN
    RAISE EXCEPTION 'Eşlemenin programı bu kurumda değil.' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.karar_veren_kisi_id IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM kisi k WHERE k.id = NEW.karar_veren_kisi_id AND k.kurum_id = NEW.kurum_id) THEN
    RAISE EXCEPTION 'Eşleme kararını veren kişi bu kurumda değil.' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$$;
